\set ON_ERROR_STOP on
\getenv auth_password AUTH_DB_PASSWORD
\getenv ai_password AI_DB_PASSWORD

CREATE ROLE auth_app LOGIN PASSWORD :'auth_password';
CREATE ROLE ai_app LOGIN PASSWORD :'ai_password';
CREATE DATABASE auth_db OWNER auth_app;
CREATE DATABASE ai_db OWNER ai_app;
REVOKE CONNECT, TEMPORARY ON DATABASE auth_db FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE ai_db FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE auth_db TO auth_app;
GRANT CONNECT, TEMPORARY ON DATABASE ai_db TO ai_app;
